#!/usr/bin/env node
//
// gen-tw-sources.mjs — tell Tailwind which components this brand actually uses.
//
// ── WHY ─────────────────────────────────────────────────────────────────────
// src/styles/global.css is a bare `@import "tailwindcss"` with no config and no
// @source, so Tailwind 4 falls back to automatic source detection and scans
// every file in the project. That is the right default almost everywhere, and
// the wrong one here.
//
// This repo carries 82 components for ~19 slots. The other 63 are inventory for
// the next brand — deliberately kept, never rendered — and every hardcoded hex
// in them still produces a utility class in the stylesheet. Measured before this
// script existed: 71% of the utilities layer (about 143 kB) matched no class in
// any built page. Those were PRODED888's gold, WINUP888's shadows, LAPDEE88's
// borders — shipped to every visitor of a brand that has nothing to do with any
// of them.
//
// The exclusion list cannot be written by hand, because which components are
// live changes on every rebrand and a stale hand-written list is worse than
// none: it would exclude a component the current brand renders, and the site
// would come out unstyled. So it is derived from the imports instead, on every
// build, by npm's prebuild hook.
//
// ── FAILURE MODE ────────────────────────────────────────────────────────────
// Deliberately biased. If anything here throws, or the import graph cannot be
// read, the generated file is emitted EMPTY — which restores Tailwind's
// scan-everything default. The worst outcome is a stylesheet as large as it was
// before this script existed. It must never be "some CSS is missing", because
// that ships a broken-looking page and nothing in the build would notice.
//
// Only files under src/components/ are ever excluded. Everything else —
// src/pages, src/layouts, src/lib, and any class string living outside a
// component — keeps being scanned exactly as before.

import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SRC = path.join(ROOT, "src");
const COMPONENTS = path.join(SRC, "components");
const OUT = path.join(SRC, "styles", "_sources.generated.css");

const HEADER = `/* GENERATED by tools/gen-tw-sources.mjs — do not edit.
 *
 * Regenerated on every \`npm run build\` (and \`npm run dev\`) by the prebuild /
 * predev hook. Editing this file by hand is pointless: the next build
 * overwrites it. To change what is excluded, change the imports.
 *
 * Each line below is a component in src/components/ that nothing reachable from
 * src/pages or src/layouts renders. It is inventory for a future brand, so its
 * hardcoded colours must not end up in this brand's stylesheet.
 */
`;

/** Entry points: everything a build can actually render. */
const ENTRY_DIRS = [path.join(SRC, "pages"), path.join(SRC, "layouts")];

function walk(dir, test, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, test, out);
    else if (test(entry.name)) out.push(p);
  }
  return out;
}

const isSource = (name) => /\.(astro|ts|tsx|js|jsx|mjs)$/.test(name);

/**
 * Component filenames imported by a file.
 *
 * Matched by BARE FILENAME, not by path. A page writes
 * `from "../components/X.astro"` but a component importing a sibling writes
 * `from "./X.astro"` — a check built on the first shape alone reports every
 * component reached only from another component as unused. That exact mistake
 * once cleared ContentBoxTwo (rendered by LoginRtpSection) as dead, and here it
 * would have deleted its styles from the build.
 */
function importedComponents(file) {
  let text;
  try {
    text = fs.readFileSync(file, "utf8");
  } catch {
    return [];
  }
  const names = new Set();
  for (const m of text.matchAll(/from\s*["']([^"']+\.astro)["']/g)) {
    names.add(path.basename(m[1]));
  }
  // Astro components can also be pulled in without a `from` clause in a few
  // shapes (dynamic import, side-effect import). Catch any literal that names
  // an .astro file, from anywhere in the file.
  for (const m of text.matchAll(/["'`]([^"'`\n]*\/)?([A-Za-z0-9_-]+\.astro)["'`]/g)) {
    names.add(m[2]);
  }
  return [...names];
}

function main() {
  if (!fs.existsSync(COMPONENTS)) return "";

  const all = new Set(fs.readdirSync(COMPONENTS).filter((f) => f.endsWith(".astro")));

  // Breadth-first from the entry points through component -> component imports.
  const reached = new Set();
  const queue = ENTRY_DIRS.flatMap((dir) => walk(dir, isSource));

  while (queue.length) {
    const file = queue.pop();
    for (const name of importedComponents(file)) {
      if (!all.has(name) || reached.has(name)) continue;
      reached.add(name);
      queue.push(path.join(COMPONENTS, name));
    }
  }

  const unused = [...all].filter((name) => !reached.has(name)).sort();

  // A result this extreme means the walk failed, not that the site renders
  // nothing. Bail out to the scan-everything default rather than emit it.
  if (reached.size === 0) {
    console.warn("gen-tw-sources: no components reachable from src/pages — falling back to scanning everything");
    return "";
  }

  const lines = unused.map((name) => `@source not "../components/${name}";`);

  // src/pages-disabled holds pages parked by a rebrand. They are not routed and
  // not built, so their classes have no business in the stylesheet.
  if (fs.existsSync(path.join(SRC, "pages-disabled"))) {
    lines.push(`@source not "../pages-disabled";`);
  }
  // tools/ is the uploader's own UI — a full HTML page inside a .mjs string.
  // Nothing there is served from this site.
  lines.push(`@source not "../../tools";`);

  console.log(`gen-tw-sources: ${reached.size} component(s) live, ${unused.length} excluded`);
  return lines.join("\n") + "\n";
}

let body = "";
try {
  body = main();
} catch (err) {
  // See FAILURE MODE above: an empty body is the safe answer.
  console.warn(`gen-tw-sources: ${err.message} — falling back to scanning everything`);
  body = "";
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, HEADER + body);
